# quantize_model.py
# W8 -- shrink the trained model and convert it to C code the ESP32-S3
# can actually compile and run.
#
# Produces three files:
#   fall_model.tflite            -- the quantized model itself
#   fall_model_data.h            -- the model as a C byte array (for firmware)
#   fall_model_quant_params.h    -- int8 scale/zero-point (needed to read
#                                    the quantized model's output correctly)
#
# Also copies over normalization.npz's mean/std into a C header, since
# the ESP32 needs to apply the SAME normalization to raw sensor readings
# that prepare_data.py applied during training -- otherwise the model
# will be fed numbers in a completely different range than it learned on.

import numpy as np
import tensorflow as tf

model = tf.keras.models.load_model("fall_model.keras")


# ---------------------------------------------------------
# STEP 1: QUANTIZE
# ---------------------------------------------------------
# The quantizer needs real example inputs to figure out the actual
# numeric range your data lives in, so it can compress floats down to
# int8 without destroying accuracy. We give it real training windows,
# not random data.

trainData = np.load("traindata.npz")
trainX = trainData["X"]

def representative_dataset():
    # A few hundred real windows is enough -- we're not retraining,
    # just showing the quantizer what "typical" values look like.
    for i in range(min(300, len(trainX))):
        sample = trainX[i:i + 1].astype(np.float32)
        yield [sample]

converter = tf.lite.TFLiteConverter.from_keras_model(model)
converter.optimizations = [tf.lite.Optimize.DEFAULT]
converter.representative_dataset = representative_dataset

# Full integer quantization -- this is what actually shrinks memory
# usage and speeds up inference enough to matter on an embedded chip.
converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
converter.inference_input_type = tf.int8
converter.inference_output_type = tf.int8

tflite_model = converter.convert()

with open("fall_model.tflite", "wb") as f:
    f.write(tflite_model)

print(f"Saved fall_model.tflite ({len(tflite_model)} bytes)")


# ---------------------------------------------------------
# STEP 2: GET THE INT8 SCALE/ZERO-POINT
# ---------------------------------------------------------
# Quantized models don't output a plain 0-1 probability directly -- they
# output an int8 number that needs to be converted back using these two
# values. The firmware needs them to make sense of the model's answer.

interpreter = tf.lite.Interpreter(model_content=tflite_model)
input_details = interpreter.get_input_details()[0]
output_details = interpreter.get_output_details()[0]

input_scale, input_zero_point = input_details["quantization"]
output_scale, output_zero_point = output_details["quantization"]

print(f"\nInput quantization -- scale: {input_scale}, zero_point: {input_zero_point}")
print(f"Output quantization -- scale: {output_scale}, zero_point: {output_zero_point}")

with open("fall_model_quant_params.h", "w") as f:
    f.write("// Auto-generated by quantize_model.py\n")
    f.write("#ifndef FALL_MODEL_QUANT_PARAMS_H\n#define FALL_MODEL_QUANT_PARAMS_H\n\n")
    f.write(f"const float INPUT_SCALE = {input_scale}f;\n")
    f.write(f"const int INPUT_ZERO_POINT = {input_zero_point};\n\n")
    f.write(f"const float OUTPUT_SCALE = {output_scale}f;\n")
    f.write(f"const int OUTPUT_ZERO_POINT = {output_zero_point};\n\n")
    f.write("#endif\n")

print("Saved fall_model_quant_params.h")


# ---------------------------------------------------------
# STEP 3: CONVERT THE MODEL ITSELF TO A C ARRAY
# ---------------------------------------------------------
# The chip can't load a .tflite file from disk the way your laptop
# does -- it needs the model's bytes compiled directly into the
# firmware as a big array. This does the same job as the "xxd" tool
# mentioned in your original plan, just in Python so it works the same
# on any operating system.

def convert_to_c_array(tflite_path, header_path, array_name="fall_model_data"):
    with open(tflite_path, "rb") as f:
        data = f.read()

    with open(header_path, "w") as f:
        f.write(f"// Auto-generated from {tflite_path}\n")
        f.write("#ifndef FALL_MODEL_DATA_H\n#define FALL_MODEL_DATA_H\n\n")
        f.write(f"alignas(8) const unsigned char {array_name}[] = {{\n")
        for i, byte in enumerate(data):
            f.write(f"0x{byte:02x}, ")
            if (i + 1) % 12 == 0:
                f.write("\n")
        f.write(f"\n}};\nconst int {array_name}_len = {len(data)};\n\n")
        f.write("#endif\n")

    print(f"Saved {header_path} ({len(data)} bytes)")

convert_to_c_array("fall_model.tflite", "fall_model_data.h")


# ---------------------------------------------------------
# STEP 4: EXPORT NORMALIZATION VALUES TOO
# ---------------------------------------------------------
# The ESP32 needs to apply the exact same (value - mean) / std
# normalization to raw sensor readings that prepare_data.py used during
# training, or the model will be looking at numbers in a totally
# different range than it learned on.

normalization = np.load("normalization.npz")
mean = normalization["mean"]
std = normalization["std"]

with open("normalization_params.h", "w") as f:
    f.write("// Auto-generated by quantize_model.py\n")
    f.write("#ifndef NORMALIZATION_PARAMS_H\n#define NORMALIZATION_PARAMS_H\n\n")
    f.write("// Order: accel_x, accel_y, accel_z, gyro_x, gyro_y, gyro_z\n")
    f.write("const float SENSOR_MEAN[6] = {" +
            ", ".join(f"{v}f" for v in mean) + "};\n")
    f.write("const float SENSOR_STD[6] = {" +
            ", ".join(f"{v}f" for v in std) + "};\n\n")
    f.write("#endif\n")

print("Saved normalization_params.h")

print("\nDone. Copy these three .h files into your ESP-IDF project's "
      "main/ folder:")
print("  fall_model_data.h")
print("  fall_model_quant_params.h")
print("  normalization_params.h")
